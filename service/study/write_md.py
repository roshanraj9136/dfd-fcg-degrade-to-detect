"""Render results/accuracy_study/upgrade.json as results/accuracy_study.md (no number is typed by hand).
python service/study/write_md.py"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
U = json.load(open(ROOT / "results" / "accuracy_study" / "upgrade.json"))
CONDS = [("clean", "as it is"), ("GB_5", "strong blur"), ("VC_5", "heavy compression")]


def pc(v):
    return "–" if v is None else f"{v * 100:.1f}%"


def au(v):
    return "–" if v is None else f"{v:.3f}"


def pts(v):
    return "–" if v is None else f"{v * 100:+.1f}"


st, sel = U["settings"], U["select"]
L = [
    "# Accuracy study: version 2 of the live checker",
    "",
    "Generated by `service/study/write_md.py` from `results/accuracy_study/upgrade.json`.",
    "",
    "Version 2 keeps the model, the weights and the self-calibration. It changes how the website uses them:",
    f"{st['clips']} clips from the first {st['window_s']:g} s instead of 2 clips from the first 144 frames (version 1 = the research",
    f"layout), every clear face (up to {st['faces']}, the most suspicious decides) instead of the largest one, mirrored clips "
    f"{'on' if st['mirror'] else 'off'}, and a \"not sure\" label when |p - 0.5| < {st['cert_margin']:.2f}.",
    "",
    "## Protocol",
    "",
    f"1. **Selection set** ({sel['used']} usable of {sel['videos']} videos, `service/study/select_set.py`): FF++ official test videos",
    "   that are not in any reported result, plus 20 new DFDC real/fake pairs. All settings and the margin were chosen here",
    "   (`study_report.py --cert`).",
    f"2. **Test set** ({U['videos']} videos, {U['failed']} could not be checked): the same FF++ test split, FaceShifter and DFDC",
    "   videos as every earlier result, each with the three website options. Run once, after the choice.",
    "3. Both versions are scored from the same run (`service/study/study.py`), so face finding is identical.",
    "",
    "## Version 1 vs version 2 on the test set",
    "",
    "| group | option | accuracy v1 → v2 | real called fake v1 → v2 | fakes caught v1 → v2 | AUROC v1 → v2 | original DFD-FCG acc. |",
    "|---|---|---|---|---|---|---|",
]
for g, gname in [("ffpp", "FF++"), ("fsh", "FF++ real + FaceShifter"), ("dfdc", "DFDC")]:
    for c, cname in CONDS:
        x = U["groups"][g][c]
        a, b = x["v1"], x["v2"]
        L.append(f"| {gname} | {cname} | {pc(a['acc'])} → {pc(b['acc'])} | {pc(a['false_alarm'])} → {pc(b['false_alarm'])} | "
                 f"{pc(a['caught'])} → {pc(b['caught'])} | {au(a['auroc'])} → {au(b['auroc'])} | {pc(x['orig']['acc'])} |")
L += ["", "## Is the gain more than noise?", "",
      "Paired, stratified bootstrap over videos (2,000 resamples); statistic: balanced accuracy averaged over the three options.",
      "", "| group | change (points) | 95% interval | answers fixed / broken | McNemar p |", "|---|---|---|---|---|"]
for g, sgn in U["significance"].items():
    L.append(f"| {g} | {pts(sgn['delta'])} | {pts(sgn['ci95'][0])} to {pts(sgn['ci95'][1])} | {sgn['fixed']} / {sgn['broken']} | {sgn['mcnemar_p']:.3f} |")
L += ["", "## \"Sure\" answers on the test set", "", "| answers | share marked sure | accuracy if sure | accuracy if not sure |", "|---|---|---|---|"]
for k, n in [("clean", "FF++ + FaceShifter, as it is"), ("GB_5", "FF++ + FaceShifter, strong blur"), ("VC_5", "FF++ + FaceShifter, heavy compression"),
             ("dfdc", "DFDC, all options"), ("all", "all")]:
    s = U["sure"][k]
    L.append(f"| {n} | {pc(s['share'])} | {pc(s['acc_sure'])} | {pc(s['acc_unsure'])} |")
L += ["", "## Every setting tried (balanced accuracy, mean of the three options)", "",
      "| clips | mirrored | faces | selection FF++ | selection DFDC | test FF++ | test DFDC |", "|---|---|---|---|---|---|---|"]
for a, t in zip(U["ablation"]["select"], U["ablation"]["test"]):
    L.append(f"| {'8 / 10 s' if a['layout'] == 'new' else '2 / 4.8 s'} | {'yes' if a['flip'] else 'no'} | {a['faces']} | "
             f"{pc(a.get('ffpp', {}).get('bacc'))} | {pc(a.get('dfdc', {}).get('bacc'))} | {pc(t.get('ffpp', {}).get('bacc'))} | {pc(t.get('dfdc', {}).get('bacc'))} |")
if U["two_face"]:
    L += ["", "## Test videos with two people", ""]
    L += [f"* {t['vid']} ({'fake' if t['label'] else 'real'}): p(fake) {t['v1']:.3f} → {t['v2']:.3f}" for t in U["two_face"]]
if U["errors"]:
    L += ["", "## Videos that could not be checked", ""] + [f"* {e}" for e in U["errors"]]
(ROOT / "results" / "accuracy_study.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("written", ROOT / "results" / "accuracy_study.md")
